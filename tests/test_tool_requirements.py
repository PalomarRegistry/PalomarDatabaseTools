def test_live_python_advisory_surveillance_is_bounded_and_least_authority():
    validate = VALIDATE.read_text(encoding="utf-8")
    sweep = (ROOT / ".github/workflows/whole-database-sweep.yml").read_text(
        encoding="utf-8"
    )

    assert validate.count("python -m pip_audit") == 1
    validate_step = workflow_step(
        validate, "Audit the reviewed production closure against live advisories"
    )
    validate_audit = validate_step.split("python -m pip_audit", 1)[1]
    assert validate_audit.startswith("\n          " + AUDIT_ARGUMENTS)
    assert "if: steps.runtime-closure.outputs.audit_changed == 'true'" in validate_step
    assert "timeout-minutes: 5" in validate_step

    python_job = workflow_job(sweep, "python-dependencies")
    assert "secrets." not in python_job
    assert "permissions:" not in python_job
    assert "persist-credentials: false" in python_job
    assert 'python-version: "3.11.10"' in python_job
    assert "--require-hashes --no-deps --only-binary=:all:" in python_job
    assert "-r requirements-test.txt" in python_job
    assert "python -m pip check" in python_job
    assert python_job.count("python -m pip_audit") == 1
    assert "timeout-minutes: 5" in python_job.rsplit("python -m pip_audit", 1)[
        0
    ].rsplit("- name:", 1)[1]
    assert python_job.split("python -m pip_audit", 1)[1].startswith(
        "\n          " + AUDIT_ARGUMENTS
    )

    for workflow in (validate, python_job):
        assert "--requirement requirements-tools.txt" in workflow
        assert "--requirement requirements-test.txt" not in workflow
        assert "--fix" not in workflow
        assert "--ignore-vuln" not in workflow
        assert "--vulnerability-service pypi" in workflow

    assert sweep.startswith("name: Whole-database sweep\n")
    trigger = sweep.split("\non:\n", 1)[1].split("\npermissions:\n", 1)[0]
    assert trigger == '  schedule:\n    - cron: "23 4 * * 1"\n  workflow_dispatch:\n'
    assert sweep.split("\npermissions:\n", 1)[1].split("\nconcurrency:\n", 1)[0] == (
        "  contents: read\n"
    )
    assert validate.split("\npermissions:\n", 1)[1].split("\njobs:\n", 1)[0] == (
        "  contents: read\n"
    )
