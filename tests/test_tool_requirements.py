def requirement_blocks(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8")
    header, separator, body = text.partition("\n\n")
    assert separator, f"{path.name} has no generated-lock header boundary: {header!r}"
    return re.split(r"\n(?=[a-zA-Z0-9])", body.strip())


def package_names(path: Path) -> set[str]:
    return {block.split("==", 1)[0] for block in requirement_blocks(path)}


def workflow_step(workflow: str, name: str) -> str:
    marker = f"      - name: {name}\n"
    _, separator, remainder = workflow.partition(marker)
    assert separator, f"workflow has no {name!r} step"
    return remainder.split("\n      - ", 1)[0]


def workflow_job(workflow: str, name: str) -> str:
    marker = f"\n  {name}:\n"
    _, separator, remainder = workflow.partition(marker)
    assert separator, f"workflow has no {name!r} job"
    next_job = re.search(r"\n  [a-z][a-z0-9-]*:\n", remainder)
    return remainder if next_job is None else remainder[: next_job.start()]


